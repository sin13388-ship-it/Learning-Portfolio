package org.example.Class;

public class P18_MathClass {
    /*
    * 常用數學函數
    *
    *
    * */
    static void main(String[] args) {
        System.out.printf("Math.toDegrees(2PI) = %.3f \n", Math.toDegrees(2*Math.PI));

        System.out.printf("Math.toRadians(360) = %.3f \n", Math.toRadians(360));
        System.out.printf("Math.toRadians(45) = %.3f \n", Math.toRadians(90));

        System.out.printf("Math.sin(PI/2) = %.3f \n", Math.sin(Math.PI /2));
        System.out.printf("Math.cos(PI/2) = %.3f \n", Math.cos(Math.PI /2));

    }


}
